<!-- Auto-generated by generate-harvest.ps1 - do not edit. -->
<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs">
  <Package Name="TubeMailGorilla" Manufacturer="TubeMailGorilla"
           Version="1.0.0" UpgradeCode="$upgradeCode"
           Scope="perMachine" Compressed="yes" InstallerVersion="500">

    <MajorUpgrade DowngradeErrorMessage="A newer version of TubeMailGorilla is already installed." />
    <MediaTemplate EmbedCab="yes" MaximumUncompressedMediaSize="4" />

    <Property Id="MODELDOWNLOADURL" Value="https://huggingface.co/bartowski/Llama-3.2-3B-Instruct-GGUF/resolve/main/Llama-3.2-3B-Instruct-Q4_K_M.gguf" />

    <Binary Id="ModelDownloadCA" SourceFile="$caEsc" />
    <SetProperty Id="DownloadModelAction" Value="INSTALLFOLDER=[INSTALLFOLDER];MODELDOWNLOADURL=[MODELDOWNLOADURL]" Before="DownloadModelAction" Sequence="execute" />
    <CustomAction Id="DownloadModelAction" BinaryRef="ModelDownloadCA" DllEntry="DownloadLlamaModel" Execute="deferred" Impersonate="no" Return="check" />
    <InstallExecuteSequence>
      <Custom Action="DownloadModelAction" After="InstallFiles" Condition="NOT Installed" />
    </InstallExecuteSequence>

    <Feature Id="Main" Title="TubeMailGorilla" Description="TubeMailGorilla desktop application" Level="1">
        <ComponentRef Id="ShortcutComponent" />
$($refsXml)    </Feature>

    <StandardDirectory Id="ProgramFiles64Folder">
      <Directory Id="INSTALLFOLDER" Name="TubeMailGorilla">
$($rootXml)      </Directory>
$($dirXml)    </StandardDirectory>

    <StandardDirectory Id="ProgramMenuFolder">
      <Directory Id="AppMenuFolder" Name="TubeMailGorilla">
        <Component Id="ShortcutComponent" Guid="C1D2E3F4-A5B6-4C7D-8E9F-0A1B2C3D4E5F">
          <Shortcut Id="AppShortcut" Name="TubeMailGorilla"
                    Description="TubeMailGorilla - YouTube lead extraction"
                    Target="[INSTALLFOLDER]TubeMailGorilla.Maui.exe"
                    WorkingDirectory="INSTALLFOLDER" />
          <RemoveFolder Id="RemoveAppMenuFolder" Directory="AppMenuFolder" On="uninstall" />
          <RegistryValue Root="HKCU" Key="Software\TubeMailGorilla" Name="ShortcutInstalled"
                         Type="integer" Value="1" KeyPath="yes" />
        </Component>
      </Directory>
    </StandardDirectory>
  </Package>
</Wix>
"@

[System.IO.File]::WriteAllText($OutFile, $doc, [System.Text.UTF8Encoding]::new($false))
Write-Host "Harvested $($componentIds.Count) files across $($dirIds.Count) directories -> $OutFile"

